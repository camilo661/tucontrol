package com.tucontrol.domain.model

/** Platform-agnostic remote control keys. Each protocol maps them to its own codes. */
enum class RemoteKey {
    POWER,
    VOLUME_UP,
    VOLUME_DOWN,
    MUTE,
    CHANNEL_UP,
    CHANNEL_DOWN,
    UP,
    DOWN,
    LEFT,
    RIGHT,
    OK,
    BACK,
    HOME,
    MENU,
    INPUT,
    PLAY_PAUSE,
    PLAY,
    PAUSE,
    STOP,
    REWIND,
    FAST_FORWARD,
}
